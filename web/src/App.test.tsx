/**
 * `App`, mounted and driven by the keyboard.
 *
 * **This file is the first thing on this branch that executes `App.tsx` at
 * all.** Tasks 11–13 pulled every testable rule out of it into modules that
 * are unit-tested at 100%; what is left is the wiring between them, and wiring
 * is exactly the thing a unit test cannot see. Every test below is here
 * because it crosses a module boundary — a keypress reaching `keys.ts`, then
 * `keyplan.ts`, then `session.ts`, then `pairing.ts`, and finally an `<img
 * src>` — or because it pins a rule that lives in `App.tsx` itself and
 * nowhere else (the six mirror refs, the refs assigned during render,
 * `resolver.dispose()` after a correction lands and never before). The order
 * the load's five reads happen in is deliberately *not* pinned here: it is
 * `startup.ts`'s property (see that file's own `openFirstWork` tests), and
 * `STARTUP_PORTS` binds each read by name with an incompatible type per
 * field, so no change to `App.tsx` can put them out of order without failing
 * to compile.
 *
 * ### Why this file can exist, when `App.tsx`'s own header says it cannot
 *
 * That header is about `wasmResolver`: `resolver.ts` value-imports
 * `taiyaku-wasm`, whose package is generated by `./scripts/build-wasm.sh`
 * into a gitignored directory, so a test importing it would pass on a machine
 * that has run that script and break CI and every fresh clone.
 *
 * `vi.mock` is what lifts that, and only for this file. Both mocks below are
 * load-bearing and neither is redundant:
 *
 * - `vi.mock('./resolver')` replaces the module outright, so `resolver.ts` is
 *   never evaluated and `App.tsx` gets a `wasmResolver` this file controls.
 * - `vi.mock('taiyaku-wasm')` is the same guard one level down, kept because
 *   `resolver.test.ts` proves it works with the package absent and because an
 *   import reaching `taiyaku-wasm` by some other route later should fail
 *   loudly here rather than only in CI.
 *
 * **Verified with `crates/taiyaku-wasm/pkg` genuinely absent**, in a fresh
 * clone, which is the property `docs/ci.md` records and CI depends on.
 *
 * The constraint stays in force for every *other* module: nothing extracted in
 * Tasks 11–13 may value-import `resolver.ts`, and this file lifting it for
 * `App.tsx` is not permission to lift it anywhere else.
 *
 * ### `jsdom`, and what it cannot answer
 *
 * A `.test.tsx` runs in the `jsdom` project, which has no layout engine
 * (`getBoundingClientRect` is all zeroes) and no real
 * `HTMLImageElement.decode()`. So nothing here asserts geometry. What it does
 * assert is which element is on screen, which `src` an `<img>` carries, what
 * reached `localStorage`, what reached the mocked API, and whether an event's
 * default was prevented — all of which jsdom answers honestly.
 */
