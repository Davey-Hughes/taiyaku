// ---- the harness ------------------------------------------------------------

/**
 * The real `setTimeout`, captured before any test fakes it.
 *
 * `settle` below needs one real macrotask — the point at which every pending
 * microtask has run — and the component's own `setTimeout`s must stay faked
 * for the whole of that, so the two cannot be the same function.
 */
const realSetTimeout = globalThis.setTimeout

/**
 * Let everything already in flight finish, without moving the clock.
 *
 * A load is five awaited promises deep and a page turn goes through
 * `decode.ts`'s queue and `cohort.ts`'s deferred close, so a bare
 * `await Promise.resolve()` is not enough to see the `<img>` change.
 */
async function settle() {
  await act(async () => {
    await new Promise((resolve) => realSetTimeout(resolve, 0))
  })
}

/** Run the reader's own clock forward by `ms`, then let what it started finish. */
async function advance(ms: number) {
  await act(async () => {
    vi.advanceTimersByTime(ms)
  })
  await settle()
}

async function open(): Promise<HTMLElement> {
  const host = mount(<App />)
  await settle()
  return host
}

/**
 * One `keydown`, dispatched at a real element so `event.target` is what a
 * browser would report — which is the whole of `keys.ts`'s `isInteractiveTarget`
 * guard, and unreachable if every event is dispatched at `window`.
 *
 * The event is handed back so a test can assert `defaultPrevented`: telling
 * `inert` (claimed, prevented, nothing happens) from `undefined` (not ours,
 * handed back to the browser) is `keyplan.ts`'s central distinction and this is
 * the only place it is observable.
 */
function press(
  key: string,
  opts: { target?: Element; shiftKey?: boolean; ctrlKey?: boolean } = {},
): KeyboardEvent {
  const event = new KeyboardEvent('keydown', {
    key,
    bubbles: true,
    cancelable: true,
    shiftKey: opts.shiftKey ?? false,
    ctrlKey: opts.ctrlKey ?? false,
  })
  act(() => {
    ;(opts.target ?? document.body).dispatchEvent(event)
  })
  return event
}

function click(el: Element) {
  act(() => {
    el.dispatchEvent(new MouseEvent('click', { bubbles: true }))
  })
}

/** React's change-tracking swallows a directly assigned `.value` — `Settings.test.tsx`'s note. */
function type(el: HTMLTextAreaElement, value: string) {
  const setter = Object.getOwnPropertyDescriptor(
    HTMLTextAreaElement.prototype,
    'value',
  )?.set
  act(() => {
    setter?.call(el, value)
    el.dispatchEvent(new Event('input', { bubbles: true }))
  })
}

const dialog = (host: HTMLElement, label: string) =>
  host.querySelector(`[role="dialog"][aria-label="${label}"]`)

/**
 * The pages the page area is drawing, by `src`. Thumbnails are excluded by
 * their own suffix rather than by walking the tree: `Filmstrip` renders one
 * `<img>` per tile from `thumbUrl`, which is `pageUrl` plus `/thumb`.
 */
const pages = (host: HTMLElement) =>
  [...host.querySelectorAll('img')]
    .map((img) => img.getAttribute('src') ?? '')
    .filter((src) => !src.includes('/thumb'))

const prefsFor = (id: string): Record<string, unknown> =>
  JSON.parse(localStorage.getItem(`taiyaku.prefs.${id}`) ?? '{}')

/** The nth `putNotes`, as its three arguments. */
const writeAt = (index: number) =>
  ports.putNotes.mock.calls[index] as [string, string, NotesDoc]

/** One module's generated section of the settings panel, found by its label. */
const section = (host: HTMLElement, label: string) =>
  [...host.querySelectorAll('h3')]
    .find((h) => h.textContent === label)
    ?.closest('section')

/** One control in it, found by `humanize`d key — the panel writes no ids. */
function field(
  host: HTMLElement,
  module: string,
  key: string,
): HTMLInputElement {
  const row = [
    ...(section(host, module)?.querySelectorAll('label') ?? []),
  ].find((l) => l.querySelector('span')?.textContent === key)
  return row?.querySelector('input') as HTMLInputElement
}

/**
 * The page area — the second child of the reader's root column, and what
 * `pageAreaRef` points at. The wheel listener and the swap's measurements are
 * both on this element rather than on the page inside it.
 */
const pageArea = (host: HTMLElement) =>
  host.firstElementChild?.children[1] as HTMLElement

const button = (host: ParentNode, text: string) =>
  [...host.querySelectorAll('button')].find(
    (b) => b.textContent === text,
  ) as HTMLButtonElement

/**
 * Give an element a layout, and an image a decoded size.
 *
 * **Nothing below asserts geometry**, and this does not start: jsdom has no
 * layout engine, so a number read back from it would be this helper's rather
 * than the reader's. What it is for is reaching the *decisions* that are gated
 * on having a box at all — `swapStep`'s four arms, the wheel's zero-box guard —
 * which are `App.tsx`'s own residual logic and are otherwise unreachable in
 * every project this gate runs. `Annotations.test.tsx` does the same, for the
 * same reason.
 */
function measure(el: Element, box: { w: number; h: number }) {
  el.getBoundingClientRect = () =>
    ({
      x: 0,
      y: 0,
      left: 0,
      top: 0,
      right: box.w,
      bottom: box.h,
      width: box.w,
      height: box.h,
      toJSON: () => ({}),
    }) as DOMRect
}

function decoded(img: HTMLImageElement, box: { w: number; h: number }) {
  Object.defineProperty(img, 'naturalWidth', {
    value: box.w,
    configurable: true,
  })
  Object.defineProperty(img, 'naturalHeight', {
    value: box.h,
    configurable: true,
  })
}

/** The `Viewport` wrapper's transform, which is the only trace `view` leaves. */
const drawnRect = (host: HTMLElement) =>
  [...host.querySelectorAll('div')].find((d) =>
    d.style.transform.startsWith('scale('),
  )?.style.transform

// ---- opening ----------------------------------------------------------------

describe('opening a work', () => {
  it('draws nothing until the load answers, then the restored page', async () => {
    const host = mount(<App />)
    // `if (!session) return null` — the reader has no loading state, by design.
    expect(host.innerHTML).toBe('')
    await settle()
    // Stored progress said `raw` slot 2, and `restore` validated it against
    // the resolver before it was trusted. The URL is `pageUrl`'s, built from
    // the `Position` the resolver gave for that slot — the whole chain from
    // `openFirstWork` through `allSlots`, `groups` and `pageAt`.
    expect(pages(host)).toEqual([
      expect.stringContaining('/vol-01/raw/pages/2'),
    ])
  })

  it('logs a failed load and stays blank rather than throwing', async () => {
    const logged = vi.spyOn(console, 'error').mockImplementation(() => {})
    ports.listWorks.mockRejectedValue(new Error('no server'))
    const host = await open()
    expect(host.innerHTML).toBe('')
    expect(logged).toHaveBeenCalledWith(expect.any(Error))
    logged.mockRestore()
  })

  it('opens the reader anyway when only the notes read fails', async () => {
    const logged = vi.spyOn(console, 'error').mockImplementation(() => {})
    ports.getNotes.mockRejectedValue(new Error('notes are down'))
    const host = await open()
    // The pages are there — a reader who cannot see their notes still gets
    // their work, which is `openFirstWork`'s one caught failure reaching the
    // component's own `notesError` log.
    expect(pages(host)).toEqual([expect.stringContaining('/raw/pages/2')])
    expect(logged).toHaveBeenCalledWith(expect.any(Error))
    logged.mockRestore()
  })

  it('does not write the position back on the load that restored it', async () => {
    await open()
    // `useProgressWrite`'s first-run skip, seen from the component: a load
    // must not `PUT` the position it was just told.
    expect(ports.putProgress).not.toHaveBeenCalled()
  })
})

// ---- the keys ---------------------------------------------------------------

describe('the reader keys', () => {
  it('Tab shows the chrome and leaves focus traversal to the browser', async () => {
    const host = await open()
    expect(host.querySelector('[role="status"]')).toBeNull()
    const event = press('Tab')
    // **`Tab` alone is `preventDefault: false`.** Preventing it is what made
    // every focusable control in the reader mouse-only, and `keyplan.ts` names
    // this as the one claimed key that does not swallow its default.
    expect(event.defaultPrevented).toBe(false)
    expect(host.querySelector('[role="status"]')).not.toBeNull()
    press('Tab')
    expect(host.querySelector('[role="status"]')).toBeNull()
  })

  it('an arrow turns the page the way the work reads', async () => {
    const host = await open()
    // `rtl`: `ArrowRight` is the physical key on the right, and `stepFor` maps
    // it to `-1` because the next page of a right-to-left work is drawn to the
    // left. Three modules and a ref assigned during render stand between the
    // keypress and this `src`.
    expect(press('ArrowRight').defaultPrevented).toBe(true)
    await settle()
    expect(pages(host)).toEqual([expect.stringContaining('/raw/pages/1')])
    press('ArrowLeft')
    press('ArrowLeft')
    await settle()
    expect(pages(host)).toEqual([expect.stringContaining('/raw/pages/3')])
  })

  it('a digit shows that edition, and Space returns to the last one', async () => {
    const host = await open()
    expect(press('2').defaultPrevented).toBe(true)
    await settle()
    expect(pages(host)).toEqual([expect.stringContaining('/vol-01/en/pages/2')])
    // `Space` is MRU, not "the authority" — it goes back to the edition being
    // left, which `applyIntent` captured on the digit press.
    press(' ')
    await settle()
    expect(pages(host)).toEqual([
      expect.stringContaining('/vol-01/raw/pages/2'),
    ])
  })

  it('a digit past the last edition is left to the browser', async () => {
    const host = await open()
    // `intentOf`'s digit row ends the walk even when it resolves to nothing, so
    // this is `undefined` rather than `inert` — the browser keeps the key.
    const event = press('9')
    expect(event.defaultPrevented).toBe(false)
    expect(pages(host)).toEqual([expect.stringContaining('/raw/pages/2')])
  })

  it('a modifier yields the key entirely', async () => {
    const host = await open()
    const event = press('ArrowRight', { ctrlKey: true })
    expect(event.defaultPrevented).toBe(false)
    await settle()
    expect(pages(host)).toEqual([expect.stringContaining('/raw/pages/2')])
  })

  it('a reader key stands down while focus is in a control', async () => {
    const host = await open()
    const button = host.querySelector('button')
    expect(button).not.toBeNull()
    // A window-level listener has no way to know a focused button is about to
    // handle the same keypress itself — so `keyPlan` hands the key back.
    const event = press('ArrowRight', { target: button as Element })
    expect(event.defaultPrevented).toBe(false)
    await settle()
    expect(pages(host)).toEqual([expect.stringContaining('/raw/pages/2')])
  })

  it('s opens and closes the settings panel', async () => {
    const host = await open()
    expect(press('s').defaultPrevented).toBe(true)
    expect(dialog(host, 'Settings')).not.toBeNull()
    press('s')
    expect(dialog(host, 'Settings')).toBeNull()
  })

  it('C opens the credits panel', async () => {
    const host = await open()
    expect(press('C').defaultPrevented).toBe(true)
    expect(dialog(host, 'Credit pages in raw')).not.toBeNull()
    press('C')
    expect(dialog(host, 'Credit pages in raw')).toBeNull()
  })

  it('C is inert — claimed, prevented, doing nothing — with the panel switched off', async () => {
    localStorage.setItem(
      'taiyaku.prefs.credits',
      JSON.stringify({ skip: false, panel: false }),
    )
    const host = await open()
    // The `inert` variant, and the reason it is not `undefined`: `App.tsx`
    // called `preventDefault()` before its module switch, so a `C` with the
    // panel off already swallowed the browser's default. Folding it into
    // "not ours" would be a behaviour change rather than an extraction.
    expect(press('C').defaultPrevented).toBe(true)
    expect(dialog(host, 'Credit pages in raw')).toBeNull()
  })

  it('? and h both open the same help overlay', async () => {
    const host = await open()
    expect(press('?').defaultPrevented).toBe(true)
    expect(dialog(host, 'Keyboard help')).not.toBeNull()
    press('h')
    expect(dialog(host, 'Keyboard help')).toBeNull()
    press('h')
    expect(dialog(host, 'Keyboard help')).not.toBeNull()
  })

  it('? is inert with the help module switched off', async () => {
    localStorage.setItem(
      'taiyaku.prefs.help',
      JSON.stringify({ enabled: false }),
    )
    const host = await open()
    expect(press('?').defaultPrevented).toBe(true)
    expect(dialog(host, 'Keyboard help')).toBeNull()
  })

  it('Escape closes the help overlay ahead of everything else', async () => {
    const host = await open()
    press('?')
    press('c')
    // Both are open; `Escape` spends itself on the one that discards nothing.
    expect(dialog(host, 'Keyboard help')).not.toBeNull()
    expect(press('Escape').defaultPrevented).toBe(true)
    expect(dialog(host, 'Keyboard help')).toBeNull()
    // The correction survived — it is the irreversible one.
    expect(host.querySelector('[role="status"]')).not.toBeNull()
  })

  it('Escape with nothing open is left to the browser', async () => {
    await open()
    expect(press('Escape').defaultPrevented).toBe(false)
  })

  it('= and - and 0 move the drawn rect, and 0 puts it back', async () => {
    const host = await open()
    const transform = () => drawnRect(host)
    const fitWhole = transform()
    expect(fitWhole).toContain('scale(1, 1)')
    expect(press('=').defaultPrevented).toBe(true)
    expect(transform()).not.toBe(fitWhole)
    press('-')
    expect(transform()).toBe(fitWhole)
    press('=')
    press('=')
    expect(transform()).not.toBe(fitWhole)
    press('0')
    expect(transform()).toBe(fitWhole)
  })

  it('= is inert in scroll mode, where nothing is drawn to zoom', async () => {
    localStorage.setItem(
      'taiyaku.prefs.layout',
      JSON.stringify({ mode: 'scroll' }),
    )
    const host = await open()
    // `drawnRef` is `undefined` in scroll mode, so `zoomable` is false and the
    // three zoom keys are claimed-but-inert. Without this, `=` in scroll mode
    // silently zooms a rect nobody is drawing and a reader finds it applied on
    // their next switch back to single.
    expect(press('=').defaultPrevented).toBe(true)
    expect(drawnRect(host)).toBeUndefined()
  })

  it('z and Z are claimed even with nothing to step through', async () => {
    const host = await open()
    // Not gated by `keyplan.ts` — the history is `App.tsx`'s and the step is a
    // ref call, so the key is claimed and `stepHistory` answers the no-op.
    expect(press('z').defaultPrevented).toBe(true)
    expect(press('Z').defaultPrevented).toBe(true)
    expect(ports.putNotes).not.toHaveBeenCalled()
    expect(pages(host)).toEqual([expect.stringContaining('/raw/pages/2')])
  })
})

