/**
 * Six pages each, paired one-for-one — except `raw` slot 5, which has no `en`
 * counterpart. That one hole is what makes a gap reachable by pressing `2` on
 * the last page, which is the only way to drive `Gap` and the `shown.kind ===
 * 'gap'` half of this component at all.
 */
function corpus(): Resolver {
  const pairs: Record<string, number> = {}
  for (let i = 0; i < 5; i++) {
    pairs[`raw|en|${i}`] = i
    pairs[`en|raw|${i}`] = i
  }
  pairs['en|raw|5'] = 5
  return {
    ...fakeResolver({ raw: whole(6), en: whole(6) }, pairs, {}, { raw: [4] }),
  }
}

const emptyNotes = (): NotesDoc => ({ work: WORK, notes: [] })

/**
 * `prefs.test.ts`'s own storage double, for the same reason it has one: the
 * bare `localStorage` `prefs.ts` reads is `globalThis`'s, and under this Node
 * that is not jsdom's — it is Node's own, which is `undefined` unless the
 * process was started with `--localstorage-file`.
 */
function fakeStorage(): Storage {
  const map = new Map<string, string>()
  return {
    get length() {
      return map.size
    },
    clear: () => map.clear(),
    getItem: (k) => map.get(k) ?? null,
    key: (i) => [...map.keys()][i] ?? null,
    removeItem: (k) => {
      map.delete(k)
    },
    setItem: (k, v) => {
      map.set(k, v)
    },
  }
}

