describe('the wheel over the page', () => {
  function wheel(el: Element, deltaY: number, ctrlKey = false) {
    const event = new WheelEvent('wheel', {
      bubbles: true,
      cancelable: true,
      deltaY,
      clientX: 40,
      clientY: 40,
      ctrlKey,
    })
    act(() => {
      el.dispatchEvent(event)
    })
    return event
  }

  it('is claimed and prevented while there is a page to zoom', async () => {
    const host = await open()
    const area = pageArea(host)
    measure(area, { w: 800, h: 600 })
    // React registers `wheel` passively, where `preventDefault()` does nothing
    // but log — so this listener is `App.tsx`'s own, non-passive, on the page
    // area. A trackpad pinch arrives as a `wheel` with `ctrlKey` set and would
    // otherwise zoom the browser's own chrome instead of the manga.
    expect(wheel(area, -120, true).defaultPrevented).toBe(true)
    expect(drawnRect(host)).not.toContain('scale(1, 1)')
    wheel(area, 120)
    expect(drawnRect(host)).toContain('scale(1, 1)')
  })

  it('is left to the browser in a gap, where nothing is drawn', async () => {
    // Off for this test only — its siblings never swap and so never reach the
    // unpaired slot. Without it "in a gap" is not what this reaches: the borrow
    // module fills the gap with a `raw` page and something *is* drawn, so the
    // test would still pass — `zoomable` is gated on `at`, which is `undefined`
    // either way — but for a different reason than the one it names, and the
    // gap's own wheel behaviour would be covered by nothing. See the
    // `beforeEach` in "a swap onto a slot with no counterpart" for the full
    // reasoning.
    localStorage.setItem(
      'taiyaku.prefs.borrow',
      JSON.stringify({ enabled: false }),
    )
    ports.getProgress.mockResolvedValue({ edition: 'raw', slot: 5 })
    const host = await open()
    const area = pageArea(host)
    measure(area, { w: 800, h: 600 })
    press('2')
    await settle()
    // Ahead of `preventDefault()`, so a wheel this declines scrolls the page
    // rather than being swallowed — which is what scroll mode already does by
    // attaching no listener at all.
    expect(wheel(area, -120).defaultPrevented).toBe(false)
  })

  it('attaches no listener at all in scroll mode', async () => {
    localStorage.setItem(
      'taiyaku.prefs.layout',
      JSON.stringify({ mode: 'scroll' }),
    )
    const host = await open()
    expect(wheel(pageArea(host), -120).defaultPrevented).toBe(false)
  })
})

// ---- the swap's second half -------------------------------------------------

describe('carrying the view across a swap', () => {
  /**
   * The two halves of a swap arrive at two different moments and neither can
   * wait for the other: `recordSwap` measures the outgoing page in the keydown
   * handler, which is the last instant it is still on screen, and the effect
   * finishes the job once the incoming one has decoded. Nothing but a mounted
   * `App` can drive both halves, and `swapView.ts`'s own tests cannot see the
   * carry surviving a re-render at all.
   */
  async function zoomedInto(): Promise<HTMLElement> {
    localStorage.setItem(
      'taiyaku.prefs.zoom',
      JSON.stringify({
        enabled: true,
        maxScale: 8,
        step: 1.15,
        onSwap: 'reset',
      }),
    )
    const host = await open()
    measure(pageArea(host), { w: 800, h: 600 })
    press('=')
    // A zoom changes the magnification `pageSize.ts` asks for, so it can change
    // the `?w=` the page is requested at — and `PageView`'s gate holds the old
    // image until the new size decodes. Settling here is what makes the `<img>`
    // on screen the one `recordSwap` is about to measure.
    await settle()
    decoded(host.querySelector('img') as HTMLImageElement, { w: 700, h: 1000 })
    return host
  }

  it('waits for the incoming page to decode, then applies the carried swap', async () => {
    const host = await zoomedInto()
    const zoomed = drawnRect(host)
    // Without this, a zoom that silently stopped applying would leave `zoomed`
    // at fit-whole and the assertions below would pass regardless. A literal
    // `-0%`/`0%` string match is not safe here — `-0` stringifies as `"0"` in
    // JS-land, so the un-zoomed and zoomed-then-reset transforms can both read
    // `translate(0%, 0%)` — so this checks the scale factor too, the same way
    // the sibling swap-into-a-gap test does.
    expect(zoomed).not.toMatch(/^scale\(1, 1\) translate\(-?0%, -?0%\)$/)
    press('2')
    await settle()
    // The incoming page is on screen but has not decoded, so `frameOf` finds
    // nothing to measure and `swapStep` answers `wait: 'undecoded'` — the view
    // is untouched and a capture-phase `load` listener is what ends the wait.
    expect(pages(host)).toEqual([expect.stringContaining('/en/pages/2')])
    expect(drawnRect(host)).toBe(zoomed)
    const img = host.querySelector('img') as HTMLImageElement
    decoded(img, { w: 1400, h: 1000 })
    act(() => {
      img.dispatchEvent(new Event('load'))
    })
    // `onSwap: 'reset'` makes the mapped rect fit-whole, which is the one
    // answer this project can assert without a layout engine — what is being
    // pinned is that the carry survived the re-render and the wait, not the
    // arithmetic, which is `viewport.ts`'s. (`-0%` or `0%` — the sign of zero
    // survives the arithmetic and says nothing about the rect.)
    expect(drawnRect(host)).toMatch(/^scale\(1, 1\) translate\(-?0%, -?0%\)$/)
  })

  it('drops a swap that lands on a gap', async () => {
    // Off for this test only — its sibling above swaps onto a real page and is
    // unaffected. **Not because the module changes the answer**: `swapStep`
    // drops on an absent `to`, `to` is `drawnRef`, and `App.tsx` assigns that
    // only when `at` is set — which `borrowed` leaves `undefined` exactly as
    // `gap` does. The carry is dropped identically either way.
    //
    // What the module changes is whether this test can *say* which state it
    // dropped in. With it on, a `raw` page is drawn where the gap was, and the
    // `pages(host)` assertion below — the one line that establishes there is
    // nothing on screen to land the view onto — fails against it. See the
    // `beforeEach` in "a swap onto a slot with no counterpart" for the full
    // reasoning; this is the same argument at one test's scope.
    localStorage.setItem(
      'taiyaku.prefs.borrow',
      JSON.stringify({ enabled: false }),
    )
    ports.getProgress.mockResolvedValue({ edition: 'raw', slot: 5 })
    const host = await zoomedInto()
    const zoomed = drawnRect(host)
    // Without this, a zoom that silently stopped applying would leave `zoomed`
    // at fit-whole and every assertion below — "the view is unchanged" — would
    // pass regardless. A literal `-0%`/`0%` string match is not safe here —
    // the sign of a zero translate is arithmetic noise, not a signal — so
    // this checks the scale factor too, the same way the carried-swap
    // assertion below already does.
    expect(zoomed).not.toMatch(/^scale\(1, 1\) translate\(-?0%, -?0%\)$/)
    press('2')
    await settle()
    // Nothing to land on: `drawnRef` is `undefined` in a gap, so the carry is
    // dropped rather than left waiting for a `load` that would never come. The
    // reader sees the view left where it was, which is the design's answer.
    expect(pages(host)).toEqual([])
    press(' ')
    await settle()
    expect(drawnRect(host)).toBe(zoomed)
  })
})

