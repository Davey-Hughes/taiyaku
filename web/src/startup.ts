/**
 * Opening a work: the five reads, in the order they have to happen, and the
 * one of them that is allowed to fail.
 *
 * Extracted from `App.tsx`'s load effect, which was 63 lines of `await` with
 * two `throw`s, one `catch` and six setters — and, being in `App.tsx`, was
 * unreachable from Vitest (see that file's own note on `resolver.ts`). What is
 * left there is the `useEffect`, its `cancelled` flag and the setters; every
 * decision about *what a load means* is here.
 *
 * The resolver arrives as a port rather than an import. That is Rule 1 of the
 * extraction map and it is a build constraint rather than a preference:
 * `resolver.ts` value-imports `taiyaku-wasm`, whose package is generated by
 * `./scripts/build-wasm.sh` into a gitignored directory, so a test importing
 * it passes on a machine that has run that script and breaks CI and every
 * fresh clone. `Resolver` as a *type* costs nothing; `wasmResolver` as a value
 * would cost the whole test file.
 */
import type {
  FetchedNotes,
  FetchedSidecar,
  StoredProgress,
  WorkSummary,
} from './api'
import type { Direction } from './modules/direction'
import type { NotesDoc } from './notes'
import { restore, type ReadingState } from './reading'
import type { Position, Resolver } from './resolver'
import { initialPrevious, orderedEditions, type Alignment } from './session'

/**
 * Enough of the sidecar to pick a work's first edition, its reading
 * direction and the verdict on a pair — `reading` is what `groups` needs to
 * know which side of a pair is drawn first, and `alignments` is what
 * `verdictFor` reads. Everything else (members, spreads, runs) stays the
 * aligner's business: the reader gets slots from the `Resolver`, below,
 * rather than deriving them here a second time.
 */
export interface SidecarShape {
  work: { reading: Direction }
  editions: Record<string, unknown>
  hub: string
  alignments: Alignment[]
}

export interface Session {
  work: string
  resolver: Resolver
  /** The sidecar's fact about the work. `d` layers a per-edition override on top of this — see `effectiveDirection`. */
  reading: Direction
  /** Digit keys index into this, in display order — see `orderedEditions`. */
  editions: string[]
  /** Read once at load, for `verdictFor` — see `SidecarShape`. */
  alignments: Alignment[]
  state: ReadingState
  /**
   * What `toggle` returns to, when currently viewing the authority. Seeded
   * at load via `session.ts`'s `initialPrevious`, never with `authority`
   * itself — see the doc there for why that seed matters.
   */
  previous: string
}

/**
 * Enough of a work listing entry to open the first one. `api.ts`'s
 * `WorkSummary` is the full row a browse screen (spec C1) will read; a load
 * only ever addresses `.slug`. `title` and `editions` stay on this `Pick`
 * rather than being dropped to just `slug` — a real caller (`listWorks`
 * itself) already has the whole `WorkSummary` and hands it through unchanged,
 * so narrowing further here would buy this file nothing.
 */
export type WorkListing = Pick<WorkSummary, 'slug' | 'title' | 'editions'>

/**
 * The five reads a load makes, injected.
 *
 * `api.ts`'s four functions and `resolver.ts`'s `wasmResolver`. Ports rather
 * than imports for two different reasons: `resolve` because of Rule 1 above,
 * and the other four because the order they are called in is the thing this
 * module is for and a test that cannot see the order cannot assert on it.
 */
export interface StartupPorts {
  works(): Promise<WorkListing[]>
  sidecar(work: string): Promise<FetchedSidecar>
  /** `wasmResolver`, injected — see this file's own doc. Never imported here. */
  resolve(json: string): Promise<Resolver>
  progress(work: string): Promise<StoredProgress | undefined>
  notes(work: string): Promise<FetchedNotes>
}

export interface Opened {
  session: Session
  etag: string | undefined
  /**
   * An empty document where the notes read failed, never `undefined`. A work
   * nobody has annotated still answers a document (`api.ts`'s `getNotes`), so
   * the reader has no empty-versus-absent case to carry either way.
   */
  notes: NotesDoc
  /**
   * Absent where the read failed, which is what makes a later write refuse:
   * `notesWrite.ts`'s `saveNotes` takes `etag: string`, and the caller's guard
   * on having one is the thing that never lets a failed read become an
   * unconditional write.
   */
  notesEtag: string | undefined
  /** The notes read's failure, for the caller to log. Absent on success. */
  notesError?: unknown
}

/**
 * Open the first work the server offers.
 *
 * Throws for "no works available" and for a work that defines no editions —
 * both are states with no reader to show, so there is nothing to degrade to.
 * The notes read is the one failure that does not stop the reader: a reader
 * who cannot see their notes should still get their pages, so it is caught
 * here and reported through `notesError` rather than rejecting.
 *
 * **The order of the five reads is load-bearing and is not an accident of how
 * this was written.** The resolver is built before progress is read, so a
 * failure parsing the sidecar surfaces before a second request is made — and
 * because `restore` needs the resolver itself, to check that a stored slot
 * still exists rather than trusting stale JSON outright. Notes are read after
 * progress rather than before it because neither depends on the other and the
 * one that can fail should not be in front of the one that cannot.
 */
export async function openFirstWork(ports: StartupPorts): Promise<Opened> {
  const [work] = await ports.works()
  if (!work) throw new Error('no works available')
  const fetched = await ports.sidecar(work.slug)
  const sidecar: SidecarShape = JSON.parse(fetched.json)
  const editions = orderedEditions(sidecar.hub, Object.keys(sidecar.editions))
  const [hub] = editions
  if (!hub) throw new Error(`${work.slug} defines no editions`)
  const resolver = await ports.resolve(fetched.json)
  const progress = await ports.progress(work.slug)
  let notesError: unknown
  const notes = await ports.notes(work.slug).catch((err: unknown) => {
    notesError = err
    return undefined
  })
  const state = restore(progress, hub, resolver)
  return {
    session: {
      work: work.slug,
      resolver,
      reading: sidecar.work.reading,
      editions,
      alignments: sidecar.alignments,
      state,
      // Not `hub`: seeding `previous` with the edition already being shown
      // would make the first `Space` (and every one after it) compute a no-op
      // target. `initialPrevious` seeds one step ahead in display order
      // instead, so the first `Space` lands where the first `2` would.
      previous: initialPrevious(editions, state.authority),
    },
    etag: fetched.etag,
    notes: notes?.doc ?? { work: work.slug, notes: [] },
    notesEtag: notes?.etag,
    notesError,
  }
}

/** Every slot of one edition, in order. `Resolver` has no bulk accessor. */
export function allSlots(resolver: Resolver, edition: string): Position[] {
  const count = resolver.slotCount(edition) ?? 0
  return Array.from(
    { length: count },
    (_, index) => resolver.slotAt(edition, index)!,
  )
}
