/**
 * `App`, mounted and driven by the keyboard.
 *
 * The testable rules live in modules that are unit-tested on their own; what
 * is left in `App.tsx` is the wiring between them, and wiring is exactly the
 * thing a unit test cannot see. Every test below is here because it crosses a
 * module boundary — a keypress reaching `keys.ts`, then `keyplan.ts`, then
 * `session.ts`, then `pairing.ts`, and finally an `<img src>` — or because it
 * pins a rule that lives in `App.tsx` itself and nowhere else (the six mirror
 * refs, the refs assigned during render, `resolver.dispose()` after a
 * correction lands and never before). The order the load's four reads happen
 * in is deliberately *not* pinned here: it is `startup.ts`'s property (see
 * that file's own `openWork` tests), and `STARTUP_PORTS` binds each read by
 * name with an incompatible type per field, so no change to `App.tsx` can put
 * them out of order without failing to compile.
 *
 * ### How this file reaches `App.tsx`
 *
 * The comment above `App.tsx`'s `wasmResolver` import is about this:
 * `resolver.ts` value-imports `taiyaku-wasm`, whose package is generated by
 * `./scripts/build-wasm.sh` into a gitignored directory, so a test importing
 * it would pass on a machine that has run that script and break CI and every
 * fresh clone.
 *
 * `vi.mock` is what lifts that, and only for this file. Both mocks below are
 * load-bearing and neither is redundant:
 *
 * - `vi.mock('../src/resolver')` replaces the module outright, so `resolver.ts` is
 *   never evaluated and `App.tsx` gets a `wasmResolver` this file controls.
 * - `vi.mock('taiyaku-wasm')` is the same guard one level down, kept because
 *   `resolver.test.ts` proves it works with the package absent and because an
 *   import reaching `taiyaku-wasm` by some other route later should fail
 *   loudly here rather than only in CI.
 *
 * Running with `crates/taiyaku-wasm/pkg` genuinely absent, as in a fresh
 * clone, is the property `docs/ci.md` records and CI depends on.
 *
 * The constraint stays in force for every *other* module: nothing extracted
 * from `App.tsx` may value-import `resolver.ts`, and this file lifting it for
 * `App.tsx` is not permission to lift it anywhere else.
 *
 * ### `jsdom`, and what it cannot answer
 *
 * A `.test.tsx` runs in the `jsdom` project, which has no layout engine
 * (`getBoundingClientRect` is all zeroes) and no real
 * `HTMLImageElement.decode()`. So nothing here asserts geometry. What it does
 * assert is which element is on screen, which `src` an `<img>` carries, what
 * reached `localStorage`, what reached the mocked API, and whether an event's
 * default was prevented — all of which jsdom answers honestly.
 */
