/** Click the nth filmstrip tile — the strip is the only surface with thumbnails. */
function pick(host: HTMLElement, index: number) {
  const tiles = [...host.querySelectorAll('button')].filter((b) =>
    (b.querySelector('img')?.getAttribute('src') ?? '').includes('/thumb'),
  )
  click(tiles[index])
}

describe('correcting a pairing', () => {
  async function confirmed(host: HTMLElement) {
    const confirm = button(host, 'Confirm')
    await act(async () => {
      confirm.dispatchEvent(new MouseEvent('click', { bubbles: true }))
      await new Promise((resolve) => realSetTimeout(resolve, 0))
    })
  }

  it('c opens the banner and forces the chrome up to pick from', async () => {
    const host = await open()
    expect(press('c').defaultPrevented).toBe(true)
    const banner = [...host.querySelectorAll('[role="status"]')].find((el) =>
      el.textContent?.includes('Pick the'),
    )
    // `counterpartEdition` picked `en` — `previous`, seeded one step ahead of
    // the authority at load, because the authority is what is on screen.
    expect(banner?.textContent).toContain('en')
    // The filmstrip is where a counterpart is picked, so `beginCorrection`
    // forces the chrome up whatever `Tab` last said, and the strip draws
    // `pending.to`'s tiles rather than the edition being read.
    const thumbs = [...host.querySelectorAll('img')].filter((img) =>
      (img.getAttribute('src') ?? '').includes('/thumb'),
    )
    expect(thumbs).toHaveLength(6)
    expect(thumbs[0].getAttribute('src')).toContain('/vol-01/en/pages/')
    // No group of `pending.to`'s is "current" while correcting — the reader is
    // still looking at `pending.from`.
    expect(host.querySelectorAll('[aria-current="true"]')).toHaveLength(0)
  })

  it('Escape abandons it and the banner goes', async () => {
    const host = await open()
    press('c')
    expect(host.textContent).toContain('Pick the')
    expect(press('Escape').defaultPrevented).toBe(true)
    expect(host.textContent).not.toContain('Pick the')
  })

  it('a second c while a write is on the wire is left alone', async () => {
    let release: (value: { json: string; etag: string }) => void = () => {}
    ports.patchAlignment.mockImplementation(
      () =>
        new Promise((resolve) => {
          release = () =>
            resolve({ json: sidecarJson('fragmented'), etag: 's2' })
        }),
    )
    const host = await open()
    press('c')
    pick(host, 3)
    click(button(host, 'Confirm'))
    // Only the submitting guard stops `c` silently replacing the correction the
    // completion handler is about to resolve: a focused button keeps only
    // `Space` and `Enter` (spec 2026-09-26 §3.2), and `disabled={submitting}`
    // blurs the just-clicked Confirm the instant the write starts anyway.
    expect(press('c').defaultPrevented).toBe(false)
    expect(press('Escape').defaultPrevented).toBe(false)
    expect(host.textContent).toContain('Writing…')
    await act(async () => {
      release({ json: sidecarJson('fragmented'), etag: 's2' })
      await new Promise((resolve) => realSetTimeout(resolve, 0))
    })
  })

  it('a landed write installs the new resolver, frees the old one, and moves the reader', async () => {
    // `resolve` held open rather than resolved immediately: call-count
    // assertions alone cannot tell "freed after the replacement exists" from
    // "freed before it does" when both land in the same microtask flush, so
    // this pins the *ordering* by checking the outgoing resolver mid-flight,
    // before the replacement is in hand at all.
    let releaseResolve: (resolver: Resolver) => void = () => {}
    ports.patchAlignment.mockResolvedValue({
      json: sidecarJson('fragmented'),
      etag: 's2',
    })
    const first = resolver
    const host = await open()
    ports.wasmResolver.mockImplementation(
      () =>
        new Promise<Resolver>((resolve) => {
          releaseResolve = resolve
        }),
    )
    press('c')
    pick(host, 3)
    click(button(host, 'Confirm'))
    await settle()
    // The write landed on the server, but its `resolve` is still on the
    // wire — no replacement resolver exists yet, so the outgoing one must
    // still be intact.
    expect(first.dispose).not.toHaveBeenCalled()
    const landedResolver = disposable()
    releaseResolve(landedResolver)
    await settle()
    // The outgoing resolver's wasm sidecar would otherwise be stranded — and it
    // is freed only now that a replacement exists, never before.
    expect(first.dispose).toHaveBeenCalledTimes(1)
    expect(landedResolver.dispose).not.toHaveBeenCalled()
    // `applyLanded` navigated the reader onto the page they picked.
    await settle()
    expect(pages(host)).toEqual([expect.stringContaining('/vol-01/en/pages/3')])
    expect(host.textContent).not.toContain('Pick the')
  })

  it('a stale validator re-reads the document and keeps the assertion', async () => {
    ports.patchAlignment.mockRejectedValue(
      new Error('correcting vol-01: 412 this work changed since you read it'),
    )
    const reread = disposable()
    const first = resolver
    const host = await open()
    ports.getSidecarWithEtag.mockResolvedValue({
      json: sidecarJson('fragmented'),
      etag: 's9',
    })
    ports.wasmResolver.mockImplementation(async () => reread)
    press('c')
    pick(host, 3)
    await confirmed(host)
    // Both or neither: the resolver and the alignments arrive together from one
    // document, and installing one beside the other's is the drift that
    // `alignmentsOf` closes.
    expect(first.dispose).toHaveBeenCalledTimes(1)
    expect(host.textContent).toContain('changed since it was read')
    // The assertion survives untouched — a re-read gets the reader a current
    // validator to confirm against, never a silently retried write.
    expect(host.textContent).toContain('Pair')
    expect(button(host, 'Confirm').disabled).toBe(false)
  })

  it('logs a failed re-read rather than showing it', async () => {
    const logged = vi.spyOn(console, 'error').mockImplementation(() => {})
    ports.patchAlignment.mockRejectedValue(
      new Error('correcting vol-01: 412 this work changed since you read it'),
    )
    const host = await open()
    ports.getSidecarWithEtag.mockRejectedValue(new Error('re-read failed'))
    press('c')
    pick(host, 3)
    await confirmed(host)
    // The reader is told the pairing moved under them — the fact they can act
    // on — and the fetch's own failure goes to the log instead of replacing it.
    expect(host.textContent).toContain('changed since it was read')
    expect(logged).toHaveBeenCalledWith(expect.any(Error))
    // No replacement resolver arrived, so nothing was freed.
    expect(resolver.dispose).not.toHaveBeenCalled()
    logged.mockRestore()
  })

  it('cancels from the banner as well as from Escape', async () => {
    const host = await open()
    press('c')
    pick(host, 3)
    click(button(host, 'Cancel'))
    expect(host.textContent).not.toContain('Pair')
    expect(ports.patchAlignment).not.toHaveBeenCalled()
  })

  it('a refused write says so and keeps the assertion on screen', async () => {
    ports.patchAlignment.mockRejectedValue(
      new Error('correcting vol-01: 400 nope'),
    )
    const host = await open()
    press('c')
    pick(host, 3)
    await confirmed(host)
    expect(host.textContent).toContain('400 nope')
    // The pick survives — nothing undoes a correction but another one, and
    // nothing here has been written.
    expect(host.textContent).toContain('Pair')
    expect(resolver.dispose).not.toHaveBeenCalled()
  })
})

