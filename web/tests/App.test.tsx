/**
 * One `keydown`, dispatched at a real element so `event.target` is what a
 * browser would report — which is the whole of `keys.ts`'s `controlKind`
 * guard, and unreachable if every event is dispatched at `window`.
 *
 * The event is handed back so a test can assert `defaultPrevented`: telling
 * `inert` (claimed, prevented, nothing happens) from `undefined` (not ours,
 * handed back to the browser) is `keyplan.ts`'s central distinction and this is
 * the only place it is observable.
 */
function press(
  key: string,
  opts: { target?: Element; shiftKey?: boolean; ctrlKey?: boolean } = {},
): KeyboardEvent {
  const event = new KeyboardEvent('keydown', {
    key,
    bubbles: true,
    cancelable: true,
    shiftKey: opts.shiftKey ?? false,
    ctrlKey: opts.ctrlKey ?? false,
  })
  act(() => {
    ;(opts.target ?? document.body).dispatchEvent(event)
  })
  return event
}

function click(el: Element) {
  act(() => {
    el.dispatchEvent(new MouseEvent('click', { bubbles: true }))
  })
}

/**
 * One pointer event, at a client point. File-level rather than local to `the
 * pointer on the page` — the gap section below reaches the page area with it
 * too, and `swapOntoUnpaired` is the only route there.
 */
function pointer(
  el: Element,
  type: string,
  at: { x: number; y: number },
  shiftKey = false,
) {
  act(() => {
    el.dispatchEvent(
      new PointerEvent(type, {
        bubbles: true,
        cancelable: true,
        clientX: at.x,
        clientY: at.y,
        shiftKey,
      }),
    )
  })
}

/** React's change-tracking swallows a directly assigned `.value` — `Settings.test.tsx`'s note. */
function type(el: HTMLTextAreaElement, value: string) {
  const setter = Object.getOwnPropertyDescriptor(
    HTMLTextAreaElement.prototype,
    'value',
  )?.set
  act(() => {
    setter?.call(el, value)
    el.dispatchEvent(new Event('input', { bubbles: true }))
  })
}

