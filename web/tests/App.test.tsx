/**
 * Give an element a layout, and an image a decoded size.
 *
 * **Nothing below asserts geometry**, and this does not start: jsdom has no
 * layout engine, so a number read back from it would be this helper's rather
 * than the reader's. What it is for is reaching the *decisions* that are gated
 * on having a box at all — `swapStep`'s four arms, the wheel's zero-box guard —
 * which are `App.tsx`'s own residual logic and are otherwise unreachable in
 * every project this gate runs. `Annotations.test.tsx` does the same, for the
 * same reason.
 */
function measure(el: Element, box: { w: number; h: number }) {
  el.getBoundingClientRect = () =>
    ({
      x: 0,
      y: 0,
      left: 0,
      top: 0,
      right: box.w,
      bottom: box.h,
      width: box.w,
      height: box.h,
      toJSON: () => ({}),
    }) as DOMRect
}

function decoded(img: HTMLImageElement, box: { w: number; h: number }) {
  Object.defineProperty(img, 'naturalWidth', {
    value: box.w,
    configurable: true,
  })
  Object.defineProperty(img, 'naturalHeight', {
    value: box.h,
    configurable: true,
  })
}

